"""
Лабораторная работа №2, раздел I, задание 1.1
Найти минимальное из трех чисел, введенных с клавиатуры.
"""

print("Задание 1.1. Минимальное из трех чисел")

a = float(input("Введите первое число: "))
b = float(input("Введите второе число: "))
c = float(input("Введите третье число: "))

print(f"Минимальное число: {min(a, b, c)}")

print()


"""
Лабораторная работа №2, раздел I, задание 1.2
Вывести числа из введенных, которые попадают в интервал [1, 50].
"""

print("Задание 1.2. Числа из интервала [1, 50]")

x = float(input("Введите первое число: "))
y = float(input("Введите второе число: "))
z = float(input("Введите третье число: "))

for i in [x, y, z]:  
    if 1 <= i <= 50: 
        print(i)

print()


"""
Лабораторная работа №2, раздел I, задание 1.3
Вывести последовательность [(1*m), (2*m), ..., (10*m)], используя цикл for.
"""

print("Задание 1.3. Последовательность от 1*m до 10*m")

m = float(input("Введите вещественное число m: "))

for i in range(1, 11):
    print(f"{i} * {m} = {i * m}")

print()


"""
Лабораторная работа №2, раздел I, задание 1.4
Найти сумму и количество чисел в произвольной последовательности 
целых чисел, используя цикл while.
"""

print("Задание 1.4. Обработка последовательности целых чисел")
print("Вводите целые числа (пустая строка для завершения):")

sum_numbers = 0
count_numbers = 0

while True:
    user_input = input()
    if user_input == '':
        break
    sum_numbers += int(user_input)
    count_numbers += 1

print(f"Сумма всех чисел: {sum_numbers}")
print(f"Количество всех чисел: {count_numbers}")
