"""
Лабораторная работа №2, раздел III, задание 3.6
Найти максимальный элемент, количество меньших чисел,
и сумму чисел больше 5 в массиве, переданном через аргументы командной строки.
"""

import sys


print("Задание 3.6")

# 1. Считываем массив
our_list = [int(x) for x in sys.argv[1:]]

# 2. Максимальный элемент
max_elem = max(our_list)
print(f"Максимальный элемент: {max_elem}")

# 3. Количество меньших чисел, чем максимальный элемент
count_less = sum(1 for x in our_list if x < max_elem)
print(f"Количество элементов меньше максимума: {count_less}")

# 4. Сумма чисел больших 5
sum_gt_5 = sum(x for x in our_list if x > 5)
print(f"Сумма чисел больше 5: {sum_gt_5}")
